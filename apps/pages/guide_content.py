def sections_for(role: str) -> list:
    """الأقسام المسموحة للدور ده (بالترتيب)."""
    allowed = ROLE_SECTIONS.get(role, ROLE_SECTIONS["guest"])
    return [s for s in SECTIONS if s["id"] in allowed]
